# Import libraries
from google.colab import files
import zipfile
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import os
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, plot_tree, export_text
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report
from sklearn.preprocessing import MinMaxScaler
from sklearn.utils import resample

# Load dataset
uploaded = files.upload()

with zipfile.ZipFile("spambase.zip", "r") as zip_ref:
    zip_ref.extractall("spambase_data")

os.listdir("spambase_data")
data = pd.read_csv("spambase_data/spambase.data", header=None)

# first 5 rows
data.head()

"""We uploaded the dataset and extracted it from the ZIP file to access the data."""

columns = []

with open("spambase_data/spambase.names", "r") as f:
    content = f.read()

import re

found_names = re.findall(r'^([\w\_!$#\[\]\(\);]+):', content, re.MULTILINE)

columns = found_names + ["spam"]

df = data.copy()

df.columns = columns

print("Dataset shape:")
print(df.shape)

print("\nClass distribution:")
print(df["spam"].value_counts())

print("\nClass percentage:")
print(df["spam"].value_counts(normalize=True) * 100)

print("\nMissing values:")
