"""This model was trained without limiting the depth, which may cause overfitting."""

# Test different max_depth values using validation data

depths = range(1, 21)

train_scores = []
val_scores = []

for d in depths:
    modelDepth = DecisionTreeClassifier(max_depth=d, random_state=42)
    modelDepth.fit(X_train, y_train)

    train_acc = accuracy_score(y_train, modelDepth.predict(X_train))
    val_acc = accuracy_score(y_val, modelDepth.predict(X_val))

    train_scores.append(train_acc)
    val_scores.append(val_acc)

depth_results = pd.DataFrame({
    "Depth": list(depths),
    "Train Accuracy": [f"{score * 100:.3f}" for score in train_scores],
    "Validation Accuracy": [f"{score * 100:.3f}" for score in val_scores]
})

depth_results

# Plot training and validation accuracy

plt.figure(figsize=(7,5))

plt.plot(depths, train_scores, marker='o', label='Train Accuracy')
plt.plot(depths, val_scores, marker='o', label='Validation Accuracy')

plt.xlabel("Max Depth")
plt.ylabel("Accuracy")
plt.title("Overfitting Analysis")
plt.legend()
plt.show()

"""**Choose Best Depth**

"""

# Select the best max_depth based on highest validation accuracy

best_depth = depths[val_scores.index(max(val_scores))]

print("Best max_depth:", best_depth)
print("Best Validation Accuracy:", f"{max(val_scores) * 100:.3f}")

"""We tested different max_depth values and used validation accuracy to choose the best one.

# **5- With addressing overfitting**
"""

modelAfterOverfit = DecisionTreeClassifier(max_depth=best_depth, random_state=42)

modelAfterOverfit.fit(X_train, y_train)

y_train_pred_after = modelAfterOverfit.predict(X_train)
y_test_pred_after = modelAfterOverfit.predict(X_test)

train_acc_after_overfit = accuracy_score(y_train, y_train_pred_after)
test_acc_after_overfit = accuracy_score(y_test, y_test_pred_after)

print("Decision Tree After Addressing Overfitting")
print("Best max_depth:", best_depth)
print("Train Accuracy:", f"{train_acc_after_overfit * 100:.3f}")
print("Test Accuracy:", f"{test_acc_after_overfit * 100:.3f}")

confMatAfterOverfit = confusion_matrix(y_test, y_test_pred_after)
print("\nConfusion Matrix:")

print("Classification Report After Handling Overfitting:")
print(classification_report(y_test,y_test_pred_after, target_names=["Not Spam", "Spam"]))

plt.figure(figsize=(5,4))

sns.heatmap(confMatAfterOverfit, annot=True, fmt='d', cmap='Greens')

plt.xlabel("Predicted")
