"""The model was trained on the imbalanced dataset.

# **8- Balancing**
"""

train_data = pd.concat([X_train, y_train], axis=1)

spam = train_data[train_data["spam"] == 1]
not_spam = train_data[train_data["spam"] == 0]

spam_up = resample(
    spam,
    replace=True,
    n_samples=len(not_spam),
    random_state=42
)

balanced = pd.concat([not_spam, spam_up])
balanced = balanced.sample(frac=1, random_state=42)

X_bal = balanced.drop("spam", axis=1)
y_bal = balanced["spam"]

print("Before Balancing:")
print(train_data["spam"].value_counts())

print("\nAfter Balancing:")
print(y_bal.value_counts())

"""We balanced the dataset by oversampling the minority class.

# **9- After Balancing**
"""

modelBalanced = DecisionTreeClassifier(max_depth=best_depth, random_state=42)

modelBalanced.fit(X_bal, y_bal)

y_bal_train_pred = modelBalanced.predict(X_bal)
y_bal_test_pred = modelBalanced.predict(X_test)

train_acc_bal_after = accuracy_score(y_bal, y_bal_train_pred)
test_acc_bal_after = accuracy_score(y_test, y_bal_test_pred)

print("Decision Tree After Balancing")
print("Train Accuracy:", f"{train_acc_bal_after * 100:.3f}")
print("Test Accuracy:", f"{test_acc_bal_after * 100:.3f}")


confMatBalAfter = confusion_matrix(y_test, y_bal_test_pred)

print("Classification Report After Balancing:")
print(classification_report(y_test, y_bal_test_pred, target_names=["Not Spam", "Spam"]))



plt.figure(figsize=(5,4))
sns.heatmap(confMatBalAfter, annot=True, fmt='d', cmap='Greens')
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Confusion Matrix After Balancing")
plt.show()

